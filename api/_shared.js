export function clean(value, max) {
  return typeof value === "string" ? value.trim().slice(0, max) : "";
}

export function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function json(status, body) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "Content-Type": "application/json", "Cache-Control": "no-store" },
  });
}

/** POST a lead to CRM_WEBHOOK_URL (Zoho Flow, Make, Zapier, or a CRM webhook). No-op when unset. */
export async function postToCrm(payload) {
  const url = process.env.CRM_WEBHOOK_URL?.trim();
  if (!url) return;
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
    signal: AbortSignal.timeout(8_000),
  });
  if (!res.ok) throw new Error(`CRM webhook ${res.status}`);
}
